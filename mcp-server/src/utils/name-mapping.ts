// ─── Name Mapping — tolerant loader for personas/name-mapping.json ──────────
//
// `personas/name-mapping.json` is a generated build artefact: its model
// fields are resolved from each user's gitignored model registry files, so
// the file itself is not Git-tracked (see personas/.gitignore). This module
// is the single place that reads it. It must never throw — a missing or
// malformed file is a routine post-pull state (the persona build has not
// run yet), not a reason to crash every consumer, including the MCP server's
// own start-up and the GUI server.
//
// Reload behaviour: the file's mtime is checked on every call; content is
// only re-read and re-parsed when the mtime changes (or nothing has been
// cached yet), so a persona rebuild is picked up without a process restart
// while repeated calls between rebuilds stay cheap.
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync, statSync } from 'fs';
import { join } from 'path';
import { WORKSPACE_ROOT } from './ledger-root.js';
import type { AgentRole } from '../schema/workflow-manifest-schema.js';

/**
 * Target-specific file name and agent name for a single IDE/platform.
 */
export interface TargetNames {
  /** Output filename for this target (e.g. "3-developer.md"). */
  file_name: string;
  /** Canonical agent name used to invoke/route to this agent on that platform. */
  agent_name: string;
}

/**
 * Full name-mapping entry for one agent role.
 * Loaded from `personas/name-mapping.json` — generated by the persona build.
 *
 * Ledger entries have a numeric `number` and `suite === "ledger"`.
 * Standalone and ledger-support entries have `number === null` and
 * `suite === "standalone"` or `suite === "ledger-support"`.
 *
 * The `suite`, `model`, `model_slug`, and `cc_model` fields are typed as
 * optional (`?`) for backward compatibility: entries in a `name-mapping.json`
 * generated before the multi-suite build pass (i.e. before WP-003 of the
 * model-settings plan) will not carry these fields.  In any current build the
 * fields are always present for every entry.  Consumers that depend on a fresh
 * build can treat them as defined; consumers that may load a stale file should
 * guard with `entry.suite ?? "ledger"` and `entry.model_slug ?? "inherit"`.
 */
export interface NameMappingEntry {
  /** Display order and numeric prefix (1–9) for ledger personas; null for non-ledger suites. */
  number: number | null;
  /** Machine-friendly unique identifier (e.g. "ledger-3-dev"). */
  id: string;
  /**
   * Role name.  For ledger entries this matches a canonical AgentRole value;
   * for non-ledger suites it is a free-form role string derived from the persona name.
   */
  role: string;
  /** Persona version string (e.g. "3.6.1"). */
  version: string;
  /**
   * Which persona suite this entry belongs to: "ledger", "standalone", or "ledger-support".
   * Optional for backward compatibility with pre-WP-003 builds — always present in current builds.
   */
  suite?: string;
  /**
   * Human-readable model name resolved at build time (e.g. "Claude Sonnet 4.6").
   * Optional for backward compatibility with pre-WP-003 builds — always present in current builds.
   */
  model?: string;
  /**
   * API-compatible model slug resolved at build time (e.g. "claude-sonnet-4-6" or "inherit").
   * Optional for backward compatibility with pre-WP-003 builds — always present in current builds.
   */
  model_slug?: string;
  /**
   * Claude Code model identifier resolved at build time (e.g. "inherit").
   * Optional for backward compatibility with pre-WP-003 builds — always present in current builds.
   */
  cc_model?: string;
  /** Names for the VS Code target. */
  vscode: TargetNames;
  /** Names for the Claude Code target. */
  claude_code: TargetNames;
  /** Names for the Deep Agents target. */
  deep_agents: TargetNames;
}

/** Per-role agent name mapping, keyed by role name (e.g. `"Developer"`). */
type AgentNameMap = Record<AgentRole, NameMappingEntry>;

/** Distinct failure kinds used to dedup stderr warnings — see {@link warnOnce}. */
type FailureKind = 'missing' | 'malformed' | 'non-array';

interface CacheState {
  /**
   * `mtimeMs` of the file as of the last successful parse, or `null` when
   * nothing has been successfully cached yet (file absent, or the last
   * attempt failed).
   */
  mtimeMs: number | null;
  /** Last successfully parsed map, or `null` when nothing is cached. */
  data: AgentNameMap | null;
  /**
   * Failure kind most recently warned about, or `null` after a successful
   * read. Used to dedup stderr warnings: re-warn only when the failure kind
   * changes from the last one reported, or after a success has reset it.
   */
  lastWarnedKind: FailureKind | null;
}

let cache: CacheState = { mtimeMs: null, data: null, lastWarnedKind: null };

/**
 * Writes a single stderr warning for the given failure `kind`, but only when
 * it differs from the kind last warned about (`cache.lastWarnedKind`). This
 * keeps a persistently missing or malformed file from spamming stderr on
 * every call while still re-surfacing the warning if the failure mode changes
 * (e.g. missing → malformed) or recurs after a successful read.
 */
function warnOnce(kind: FailureKind, message: string): void {
  if (cache.lastWarnedKind !== kind) {
    process.stderr.write(message);
    cache.lastWarnedKind = kind;
  }
}

/**
 * Resolves the absolute path to `personas/name-mapping.json`.
 *
 * Reads `WORKSPACE_ROOT` from `./ledger-root.js` on every call rather than
 * into a module-level constant, so that tests mocking `ledger-root.js` with
 * a getter (the pattern already used in `tests/gui/api-models.test.ts`) take
 * effect without a new override parameter.
 */
export function resolveNameMappingPath(): string {
  return join(WORKSPACE_ROOT, 'personas', 'name-mapping.json');
}

/**
 * Returns `true` when `personas/name-mapping.json` exists on disk, `false`
 * otherwise. Performs no parsing — a cheap existence check only.
 */
export function isNameMappingPresent(): boolean {
  try {
    statSync(resolveNameMappingPath());
    return true;
  } catch {
    return false;
  }
}

/**
 * Loads the per-role agent name mapping from `personas/name-mapping.json`.
 *
 * Tolerant by design: returns `{}` — never throws — when the file is
 * missing, unreadable, malformed JSON, or not a JSON array. Each distinct
 * failure kind writes exactly one stderr warning (deduplicated across
 * repeated calls with the same kind; reset after a successful read so a
 * later failure warns again). Writes nothing to stdout.
 *
 * Reload behaviour: the file's `mtimeMs` is checked on every call. Content
 * is only re-read and re-parsed when the mtime has changed since the last
 * successful parse (or nothing has been cached yet), so a persona rebuild
 * is picked up without a process restart, while repeated calls between
 * rebuilds avoid redundant file reads.
 */
export function getAgentNames(): AgentNameMap {
  const filePath = resolveNameMappingPath();

  let fileStat;
  try {
    fileStat = statSync(filePath);
  } catch {
    cache.mtimeMs = null;
    cache.data = null;
    warnOnce(
      'missing',
      `[name-mapping] ${filePath} not found; target-specific agent names are unavailable until the persona build runs.\n`
    );
    return {} as AgentNameMap;
  }

  // Cache hit: data was parsed successfully and the file has not changed since.
  if (cache.data !== null && cache.mtimeMs === fileStat.mtimeMs) {
    return cache.data;
  }

  let raw: string;
  try {
    raw = readFileSync(filePath, 'utf8');
  } catch (err) {
    cache.data = null;
    cache.mtimeMs = null;
    warnOnce('malformed', `[name-mapping] Failed to read ${filePath}: ${String(err)}\n`);
    return {} as AgentNameMap;
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    cache.data = null;
    cache.mtimeMs = null;
    warnOnce('malformed', `[name-mapping] ${filePath} is not valid JSON: ${String(err)}\n`);
    return {} as AgentNameMap;
  }

  if (!Array.isArray(parsed)) {
    cache.data = null;
    cache.mtimeMs = null;
    warnOnce('non-array', `[name-mapping] ${filePath} must be a JSON array; got ${typeof parsed}.\n`);
    return {} as AgentNameMap;
  }

  const data = Object.fromEntries(
    (parsed as NameMappingEntry[])
      .filter(entry => !entry.suite || entry.suite === 'ledger')
      .map(entry => [entry.role, entry])
  ) as AgentNameMap;

  cache.data = data;
  cache.mtimeMs = fileStat.mtimeMs;
  cache.lastWarnedKind = null; // Reset dedup so a future failure warns again.
  return data;
}

/**
 * Test-only: clears the module-level cache so each test starts from a clean
 * slate. Not exported for production use.
 */
export function _resetNameMappingCache(): void {
  cache = { mtimeMs: null, data: null, lastWarnedKind: null };
}
